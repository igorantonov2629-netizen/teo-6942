export function orderPresentation(status: string) {
  return (
    stages[status] || {
      emoji: "🔔",
      label: status,
      message: `Обновление вашего заказа: ${status}. Если нужна помощь, напишите в поддержку.`,
    }
  );
}
export function orderLabel(status: string) {
  const s = orderPresentation(status);
  return `${s.emoji} ${s.label}`;
}
export function buyerStageMessage(status: string) {
  const s = orderPresentation(status);
  return `${s.emoji} ${s.message}`;
}
export function outstandingPayment(o: Order) {
  if (o.status.startsWith("Заказ отменён")) return null;
  if (o.goodsPayment?.state === "waiting")
    return { phase: "товар", amount: o.goodsPayment.amount };
  if (o.shippingPayment?.state === "waiting")
    return { phase: "доставку", amount: o.shippingPayment.amount };
  return null;
}
export function homeOrder(orders: Order[]) {
  const active = orders.filter(
    (o) =>
      !["Заказ доставлен", "Выдан"].includes(o.status) &&
      !o.status.startsWith("Заказ отменён"),
  );
  return (
    active.find((o) => outstandingPayment(o)) ||
    active.find((o) => o.status === "Ждём согласия покупателя") ||
    active[0] ||
    orders[0]
  );
}

