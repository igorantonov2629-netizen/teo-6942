/** Stage tone, progress step (-1 when cancelled) and a one-line description for the home panel. */
export function orderJourney(status: string): {
  tone: JourneyTone;
  step: number;
  short: string;
  title: string;
} {
  if (status.startsWith("Заказ отменён")) {
    const reason = status.replace(/^Заказ отменён:?\s*/, "");
    const text =
      cancelReasons[reason] || (reason ? `${reason}.` : "заказ отменён.");
    return {
      tone: "cancelled",
      step: -1,
      short: `Причина: ${text}`,
      title: `${orderPresentation(status).emoji} Заказ отменён`,
    };
  }
  const j = journey[status] || {
    tone: "request" as const,
    step: 0,
    short: status,
  };
  return { ...j, title: orderLabel(status) };
}
